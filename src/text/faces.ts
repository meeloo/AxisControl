// The Hershey faces, as distributed in .jhf form.
//
// Dr. Allen V. Hershey drew these at the US Naval Weapons Laboratory in 1967
// for plotting on cathode ray tubes, which is why they look the way they do and
// why they suit this exactly: every glyph is already a sequence of pen-up and
// pen-down moves, so it IS a toolpath. Nothing is converted, offset or
// approximated on the way to G-code.
//
// The Hershey fonts are generally treated as public domain. The distribution
// these came from carries the customary notice, kept here because the notice
// asks to be kept:
//
//   This distribution of the Hershey Fonts may be used by anyone for any
//   purpose, commercial or otherwise, providing that:
//     1. The following acknowledgements must be distributed with the font
//        data:
//        - The Hershey Fonts were originally created by Dr. A. V. Hershey
//          while working at the U. S. National Bureau of Standards.
//        - The format of the Font data in this distribution was originally
//          created by James Hurt, Cognition Inc.
//     2. The font data in this distribution may be converted into any other
//        format EXCEPT that the acknowledgements are not removed.
//
// Six faces, ASCII 32..127 each, about 45KB in total. Embedded rather than
// fetched: a workshop machine is often not on a network, and a font that needs
// a round trip is missing exactly when you want to label the thing in front of
// you.

